export const productBySlug = Object.fromEntries(
  products.map((p) => [p.slug, p]),
) as Record<string, Product>;

export function productsInCollection(slug: string): Product[] {
  return products.filter((p) => p.collection === slug);
}

export function relatedProducts(slug: string, limit = 3): Product[] {
  const p = productBySlug[slug];
  if (!p) return [];
  const explicit = (p.relatedSlugs ?? [])
    .map((s) => productBySlug[s])
    .filter(Boolean);
  if (explicit.length >= limit) return explicit.slice(0, limit);
  const fill = products.filter(
    (x) => x.slug !== slug && x.collection === p.collection && !explicit.includes(x),
  );
  return [...explicit, ...fill].slice(0, limit);
}

export const featuredProducts = products.filter((p) => p.featured);
export const stuckOnProducts = products.filter((p) => p.stuckOn);
